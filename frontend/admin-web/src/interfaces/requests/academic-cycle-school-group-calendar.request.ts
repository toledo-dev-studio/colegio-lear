import type { EmployeeRequest } from "./employee.request";
import type { AcademicCycleRequest } from "./academic-cycle.request";
import type { SchoolSubjectRequest } from "./school-subject.request";
import type { DayOfWeekKey } from "@/lib/key-value-pairs/key-value-pair";
import type { AcademicCycleSchoolGroupRequest } from "./academic-cycle-school-group.request";

/**
 * Type: Request
 * Description: Represents the schedule for a specific within an academic cycle group, containing details about the day of the week, class schedule, and references to related entities such as the academic cycle and academic cycle group.
 */
export interface AcademicCycleSchoolGroupCalendarRequest {
    /**
     * Unique identifier for the academic cycle group calendar, generated by backend
     */
    id?: string;
    /**
     * Day of the week for the academic cycle group calendar, represented as a key from the DayOfWeekKey type (e.g., "monday", "tuesday", etc.)
     */
    day: DayOfWeekKey;
    /**
     * Start time of the class for the academic cycle group calendar, represented as an ISO string (HH:mm:ss)
     */
    startTime: string;
    /**
     * End time of the class for the academic cycle group calendar, represented as an ISO string (HH:mm:ss)
     */
    endTime: string;
    /**
     * Identifier of the associated academic cycle
     */
    academicCycleId: string;
    /**
     * Reference to the associated academic cycle
     */
    academicCycle?: AcademicCycleRequest;
    /**
     * Identifier of the associated academic cycle group
     */
    academicCycleSchoolGroupId: string;
    /**
     * Reference to the associated academic cycle group
     */
    academicCycleSchoolGroup?: AcademicCycleSchoolGroupRequest;
    /**
     * Identifier of the associated school subject
     */
    schoolSubjectId: string;
    /**
     * Reference to the associated school subject
     */
    schoolSubject?: SchoolSubjectRequest;
    /**
     * Identifier of the associated teacher (employee)
     */
    teacherId: string;
    /**
     * Reference to the associated teacher (employee)
     */
    teacher?: EmployeeRequest;
}
