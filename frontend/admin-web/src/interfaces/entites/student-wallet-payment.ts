import type { Student } from "./student";
import type { AcademicCycle } from "./academic-cycle";
import type { PaymentMethodKey } from "@/lib/key-value-pairs/key-value-pair";
import type { StudentWalletPaymentConcept } from "./student-wallet-payment-concept";

/**
 * Represents a payment made by a student towards their wallet for a specific academic cycle, containing details about the payment amount, related entities, and references to the associated payment concept.
 * Each student wallet payment is associated with a specific academic cycle, student, and student wallet payment concept, allowing for tracking payments made by students towards their outstanding balances for each academic cycle.
 */
export interface StudentWalletPayment {
    /**
     * Required - Unique identifier for the student wallet payment, generated by backend
     */
    id: string;
    /**
     * Required - Amount of the payment
     */
    amount: number;
    /**
     * Required - Payment method used for the payment
     * Example: "Online payment", "Cash"
     */
    paymentMethod: PaymentMethodKey;

    /**
     * Required - Identifier of the associated academic cycle
     */
    academicCycleId: string;
    /**
     * Not set from frontend - Reference to the associated academic cycle
     */
    academicCycle?: AcademicCycle;

    /**
     * Required - Identifier of the associated student
     */
    studentId: string;
    /**
     * Not set from frontend - Reference to the associated student
     */
    student?: Student;

    /**
     * Required - Identifier of the associated student wallet payment concept
     */
    studentWalletPaymentConceptId: string;
    /**
     * Not set from frontend - Reference to the associated student wallet payment concept
     */
    studentWalletPaymentConcept?: StudentWalletPaymentConcept;
}
