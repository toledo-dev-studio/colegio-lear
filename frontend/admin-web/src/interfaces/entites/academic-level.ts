import type { EducationLevel } from "./education-level";

/**
 * Represents an academic level within the school, containing details about the level's name, description, status, and references to related education levels.
 * This entity is used to categorize students into different academic levels based on their grade or year, allowing for better organization and management of enrollments, attendance, and other related processes.
 * Each academic level can be associated with multiple education levels, providing a structured way to manage the different stages of education within the school.
 */
export interface AcademicLevel {
    /**
     * Required - Unique identifier for the academic level, generated by backend
     */
    id: string;
    /**
     * Required - Name of the academic level
     * Example: "Primaria", "Secundaria", "Preparatoria"
     */
    name: string;
    /**
     * Optional - Description of the academic level
     * Example: "Nivel académico para estudiantes de primaria"
     */
    description?: string;
    /**
     * Required - Indicates if the academic level is active
     */
    status: boolean;
    /**
     * Required - List of education levels associated with the academic level. Can be empty if there are no associated education levels.
     */
    educationLevels: EducationLevel[]
}
