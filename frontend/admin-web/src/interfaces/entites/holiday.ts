/**
 * Represents a holiday within the school, containing details about the holiday's name, description, date range, and applicability to students and employees.
 * This entity is used to manage the holidays observed by the school, allowing for better organization and scheduling of academic activities, attendance, and other related processes.
 * Each holiday can be configured to apply to all students and employees or to specific academic cycles, academic levels, or education levels, providing flexibility in managing holidays within the school.
 */
export interface Holiday {
    /**
     * Required - Unique identifier for the holiday, generated by backend
     */
    id: string;

    /**
     * Required - Name of the holiday
     * Example: "Día de la Independencia", "Navidad"
     */
    name: string;

    /**
     * Optional - Description of the holiday
     * Example: "Celebración de la independencia del país", "Celebración del nacimiento de Jesús"
     */
    description?: string;

    /**
     * Required - Start date of the holiday, represented as an ISO string (YYYY-MM-DD)
     */
    startDate: string;

    /**
     * Required - End date of the holiday, represented as an ISO string (YYYY-MM-DD)
     */
    endDate: string;

    /**
     * Required - Indicates if the holiday applies to all students and employees regardless of their academic cycle, academic level, or education level
     */
    appliesToAll: boolean;

    /**
     * Required - Indicate if the holiday applies to a specific academic cycle
     */
    academicCycleId?: string;

    /**
     * Required - Indicate if the holiday applies to a specific academic level
     */
    academicLevelId?: string;

    /**
     * Required - Indicate if the holiday applies to a specific education level
     */
    educationLevelId?: string;

}