import type { AcademicLevel } from "./academic-level";
import type { EducationLevel } from "./education-level";

/**
 * Represents a school subject within the school, containing details about the subject's name, description, status, and references to related academic and education levels.
 * This entity is used to manage the different subjects offered by the school, allowing for better organization and assignment of subjects to academic cycle groups and teachers.
 * Each school subject is associated with a specific academic level and education level, providing a structured way to categorize and manage the subjects within the school's curriculum.
 */
export interface SchoolSubject {
    /**
     * Required - Unique identifier for the school subject, generated by backend
     */
    id: string;
    /**
     * Required - Name of the school subject
     * Example: "Matemáticas", "Español"
     */
    name: string;
    /**
     * Optional - Description of the school subject
     * Example: "Materia de matemáticas para estudiantes de primaria"
     */
    description?: string;
    /**
     * Required - Indicates if the school subject is active
     */
    status: boolean;

    /**
     * Required - Unique identifier for the associated academic level
     */
    academicLevelId: string;
    /**
     * Not set from frontend - Reference to the associated academic level
     */
    academicLevel?: AcademicLevel;

    /**
     * Required - Unique identifier for the associated education level
     */
    educationLevelId: string;
    /**
     * Not set from frontend - Reference to the associated education level
     */
    educationLevel?: EducationLevel;
}

