import type { Student } from "./student";
import type { AcademicCycle } from "./academic-cycle";
import type { AcademicCycleGroup } from "./academic-cycle-school-group";

/**
 * Represents an attendance record for a student on a specific date, containing details about the attendance status, related entities, and timestamps for record management.
 * Each attendance record is associated with a student, an academic cycle, and an academic cycle group, allowing for tracking attendance across different periods and groups.
 */
export interface Attendance {
    /**
     * Required - Unique identifier for the attendance record, generated by backend
     */
    id: string;
    /**
     * Required - Date and time of the attendance record as an ISO string (YYYY-MM-DDTHH:mm:ss.mmmZ)
     * Value set from backend when creating a new record, frontend should not set this field when creating or updating a record
     */
    attendanceDate: string;
    /**
     * Required - Indicates if the student was present (true) or absent (false)
     */
    isPresent: boolean;
    /**
     * Optional - additional notes about the attendance record, such as reasons for absence or other relevant information
     */
    observations?: string;

    /**
     * Required - Identifier of the associated academic cycle
     */
    academicCycleId: string;
    /**
     * Not set from frontend - Reference to the associated academic cycle
     */
    academicCycle?: AcademicCycle;

    /**
     * Required - Identifier of the associated academic cycle group
     */
    academicCycleGroupId: string;
    /**
     * Not set from frontend - Reference to the associated academic cycle group
     */
    academicCycleGroup?: AcademicCycleGroup;

    /**
     * Required - Identifier of the associated student
     */
    studentId: string;
    /**
     * Not set from frontend - Reference to the associated student
     */
    student?: Student;
}
