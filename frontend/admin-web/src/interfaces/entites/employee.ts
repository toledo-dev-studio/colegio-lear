import type { JobTitle } from "./job-title";
import type { SecurityRole } from "./security-role";

/**
 * Represents an employee of the school, containing their personal information, contact details, status, and references to related entities such as their job title and security role.
 * This entity is used to manage the staff members of the school, allowing for better organization and assignment of roles and responsibilities within the school's operations.
 * Each employee is associated with a specific job title and security role, providing a structured way to manage the different positions and access levels within the school.
 */
export interface Employee {
    /**
     * Required - Unique identifier for the employee, generated by backend
     */
    id: string;
    /**
     * Required - Name of the employee
     */
    name: string;
    /**
     * Required - First last name of the employee
     */
    firstLastName: string;
    /**
     * Optional - Second last name of the employee
     */
    secondLastName?: string;
    /**
     * Required - Phone number of the employee
     */    
    phoneNumber: string;
    /**
     * Required - Email address of the employee
     */
    email: string;
    /**
     * Required - Username for the employee to access the system, generated by backend
     */
    username: string;
    /**
     * Optional - URL of the employee's profile image. This field can be used to store a link to an image hosted on a cloud storage service or a local server. 
     * The frontend can display this image in the employee's profile or other relevant sections of the application, while the backend can handle the storage and retrieval of the image URL as needed.
     */
    image?: string;
    /**
     * Required - Indicates if the employee is active
     */
    status: boolean;

    /**
     * Required - Unique identifier for the associated security role
     */
    securityRoleId: string;
    /**
     * Not set from frontend - Reference to the associated security role
     */
    securityRole?: SecurityRole;

    /**
     * Required - Unique identifier for the associated job title
     */
    jobTitleId: string;
    /**
     * Not set from frontend - Reference to the associated job title
     */
    jobTitle?: JobTitle
}
