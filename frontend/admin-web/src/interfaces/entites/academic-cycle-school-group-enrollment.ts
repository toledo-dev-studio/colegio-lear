import type { Student } from "./student";
import type { Scholarship } from "./scholarship";
import type { AcademicCycle } from "./academic-cycle";
import type { AcademicCycleSchoolGroup } from "./academic-cycle-school-group";
import type { KeyValuePair, AcademicCycleSchoolGroupEnrollmentStatusKey } from "@/types/KeyValuePair";

/**
 * ACADEMIC_CYCLE_SCHOOL_GROUP_ENROLLMENT_STATUSES defines the possible statuses for a student's enrollment in an academic cycle group, which can be used to track the current state of the enrollment. 
 * Each status has a key and a label for display purposes.
 */
export const ACADEMIC_CYCLE_SCHOOL_GROUP_ENROLLMENT_STATUSES: KeyValuePair<AcademicCycleSchoolGroupEnrollmentStatusKey>[] = [
    { key: "enrolled", label: "Inscrito" },
    { key: "completed", label: "Ciclo finalizado" },
    { key: "dropped", label: "Dado de baja" },
];

/**
 * Represents the enrollment of a student in a specific academic cycle group, containing details about the enrollment status, related entities, and timestamps for record management.
 */
export interface AcademicCycleSchoolGroupEnrollment {

    /**
     * Required - Unique identifier for the student group enrollment, generated by backend
     */
    id: string;
    /**
     * Required - Current status of the student group enrollment
     */
    status: AcademicCycleSchoolGroupEnrollmentStatusKey;
    /**
     * Optional - Additional notes about the student group enrollment
     */
    observations?: string;
    /**
     * Optional - Notes about "dropped" status for a student.
     */
    droppedNotes?: string;

    /**
     * Not set from frontend - Timestamp when the record was created as an ISO string (YYYY-MM-DDTHH:mm:ss.mmmZ)
     * Backend should set this field when creating a new record, frontend should not set this field when creating or updating a record
     */
    createdAt?: string;
    /**
     * Not set from frontend - Timestamp when the record was last updated as an ISO string (YYYY-MM-DDTHH:mm:ss.mmmZ)
     * Backend should set this field when updating a record, frontend should not set this field when creating or updating a record
     */
    updatedAt?: string;

    /**
     * Required - Identifier of the associated student
     */
    studentId: string;
    /**
     * Not set from frontend - Reference to the associated student
     */
    student?: Student;

    /**
     * Required - Identifier of the associated academic cycle
     */
    academicCycleId: string;
    /**
     * Not set from frontend - Reference to the associated academic cycle
     */
    academicCycle?: AcademicCycle;

    /**
     * Required - Identifier of the associated academic cycle group
     */
    academicCycleSchoolGroupId: string;
    /**
     * Not set from frontend - Reference to the associated academic cycle group
     */
    academicCycleSchoolGroup?: AcademicCycleSchoolGroup;

    /**
     * Optional - Identifier of the scholarship associated with the student group enrollment, if applicable
     */
    scholarshipId?: string;
    /**
     * Not set from frontend - Reference to the scholarship associated with the student group enrollment, if applicable
     */
    scholarship?: Scholarship;
}
