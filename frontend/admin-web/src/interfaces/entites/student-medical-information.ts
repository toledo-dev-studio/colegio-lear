import type { BloodTypeKey, KeyValuePair } from "@/types/KeyValuePair";
import type { Allergy } from "./allergy";

/**
 * BLOOD_TYPES is a constant array of key-value pairs representing the different blood types that can be assigned to a student. 
 * Each object in the array has a 'key' which is the blood type code (e.g., "A+", "O-", etc.) and a 'label' which is the human-readable name for that blood type. This constant can be used throughout the application wherever a selection of blood types is needed, ensuring consistency and ease of maintenance.
 */
export const BLOOD_TYPES: KeyValuePair<BloodTypeKey>[] = [
    { key: "A+", label: "A+" },
    { key: "A-", label: "A-" },
    { key: "B+", label: "B+" },
    { key: "B-", label: "B-" },
    { key: "AB+", label: "AB+" },
    { key: "AB-", label: "AB-" },
    { key: "O+", label: "O+" },
    { key: "O-", label: "O-" }
];

/**
 * Represents the medical information of a student, including their blood type, any emergency notes, and a list of allergies. 
 * This information is crucial for ensuring the safety and well-being of the student while at school, allowing staff to be aware of any medical conditions or risks that may require special attention or accommodations.
 */
export interface StudentMedicalInformation {
    /**
     * Required - Unique identifier for the medical information record, generated by backend
     */
    id: string;
    /**
     * Required - Unique identifier of the student to which this medical information belongs
     */
    studentId: string;
    /**
     * Required - Blood type (e.g., "A+", "O-", etc.)
     */
    bloodType: string;
    /**
     * Optional - Medical notes or observations about the student
     */
    emergencyNotes?: string;
    /**
     * Optional - List of allergies, can be empty if none
     */
    allergies: Allergy[];
}
