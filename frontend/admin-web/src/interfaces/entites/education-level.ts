/**
 * Represents an education level within the school, containing details about the level's name, description, and reference to the associated academic level.
 * This entity is used to categorize students into different education levels based on their grade or year, allowing for better organization and management of enrollments, attendance, and other related processes.
 * Each education level is associated with a specific academic level, providing a structured way to manage the different stages of education within the school.
 */
export interface EducationLevel {
    /**
     * Required - Unique identifier for the education level, generated by backend
     */
    id: string;
    /**
     * Required - Name of the education level
     * Example: "1ro de primaria", "2do de primaria"
     */
    name: string;
    /**
     * Optional - Description of the education level
     * Example: "Grado 1 de primaria"
     */
    description?: string;
    /**
     * Required - Unique identifier for the associated academic level
     */
    academicLevelId: string;
}