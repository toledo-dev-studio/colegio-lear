import type { Employee } from "./employee";
import type { AcademicCycle } from "./academic-cycle";
import type { SchoolSubject } from "./school-subject";
import type { AcademicCycleGroup } from "./academic-cycle-group";

/**
 * Represents the association between an academic cycle group and a school subject, containing details about the status of the association, observations, and references to related entities such as the academic cycle, academic cycle group, school subject, and teacher.
 * This entity is used to manage the subjects taught in each academic cycle group, allowing for better organization of the curriculum and assignment of teachers to specific subjects within each group.
 * Each academic cycle group school subject is associated with a specific academic cycle, academic cycle group, school subject, and teacher, providing a structured way to manage the educational offerings for each group.
 */
export interface AcademicCycleGroupSchoolSubject {
    /**
     * Required - Unique identifier for the academic cycle group school subject, generated by backend
     */
    id: string;
    /**
     * Required - Indicates if the academic cycle group school subject is active
     */
    status: boolean;
    /**
     * Optional - Description of the academic cycle group school subject
     */
    observations?: string;

    /**
     * Required - Identifier of the associated academic cycle
     */
    academicCycleId: string;
    /**
     * Not set from frontend - Reference to the associated academic cycle
     */
    academicCycle?: AcademicCycle;

    /**
     * Required - Identifier of the associated academic cycle group
     */
    academicCycleGroupId: string;
    /**
     * Not set from frontend - Reference to the associated academic cycle group
     */
    academicCycleGroup?: AcademicCycleGroup;

    /**
     * Required - Identifier of the associated school subject
     */
    schoolSubjectId: string;
    /**
     * Not set from frontend - Reference to the associated school subject
     */
    schoolSubject?: SchoolSubject;

    /**
     * Required - Identifier of the associated teacher
     */
    teacherId: string;
    /**
     * Not set from frontend - Reference to the associated teacher
     * The teacher is an employee with a job title of "teacher", but this relationship is not enforced at the database level, so we use a reference to the Employee entity instead of a more specific Teacher entity.
     * Frontend should only allow selecting employees with a job title of "teacher" when setting the teacherId field, but backend should not enforce this restriction at the database level to allow for flexibility in case of changes in the future.
     */
    teacher?: Employee;
}
