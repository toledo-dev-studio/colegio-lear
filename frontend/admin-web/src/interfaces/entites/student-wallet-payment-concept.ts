import type { Student } from "./student";
import type { AcademicCycle } from "./academic-cycle";
import type { KeyValuePair, StudentPaymentStatusKey } from "@/types/KeyValuePair";
import type { AcademicCycleWallet } from "./academic-cycle-wallet";

/**
 * STUDENT_PAYMENT_STATUSES defines the possible statuses for a student's payment associated with an academic cycle wallet, which can be used to track the current state of the payment. 
 * Each status has a key and a label for display purposes.
 */
export const STUDENT_PAYMENT_STATUSES: KeyValuePair<StudentPaymentStatusKey>[] = [
    { key: "pending", label: "Pendiente" },
    { key: "paid", label: "Pagado" },
    { key: "overdue", label: "Vencido" },
    { key: "forgiven", label: "Condonado" },
    { key: "cancelled", label: "Cancelado" },
];

/**
 * Represents a payment concept associated with a student's wallet for a specific academic cycle, containing details about the payment, its status, and references to related entities.
 */
export interface StudentWalletPaymentConcept {
    /**
     * Required - Unique identifier for the academic cycle wallet, generated by backend
     */
    id: string;
    /**
     * Required - Due date for the payment associated with the academic cycle wallet as an ISO string (YYYY-MM-DDTHH:mm:ss.mmmZ)
     */
    dueDate: string;
    /**
     * Required - Amount for the payment associated with the academic cycle wallet
     * In frontend the default value will be determined by the associated payment concept, but it can be overridden when creating or updating an academic cycle wallet. 
     * If not provided, the backend should set this field to the default amount defined in the associated payment concept.
     */
    amount: number;
    /**
     * Required - Outstanding amount for the payment associated with the academic cycle wallet
     * This field represents the remaining amount to be paid after any partial payments have been made. 
     * The backend should calculate and update this field whenever a payment is made, and the frontend should display this field to inform users of the remaining balance for the payment.
     */
    outstandingAmount: number;
    /**
     * Required - Indicates if forgiveness is allowed for the payment associated with the academic cycle wallet
     * In frontend the default value will be determined by the associated payment concept, but it can be overridden when creating or updating an academic cycle wallet. 
     * If not provided, the backend should set this field to the default allowForgiveness value defined in the associated payment concept.
     */
    allowForgiveness: boolean;
    /**
     * Optional - Indicates if the payment associated with the student wallet has been forgiven.
     */
    isForgiven?: boolean;
    /**
     * Optional - Date when the payment associated with the student wallet is extended
     */
    extensionDate?: string;
    /**
     * Required - Current status of the payment associated with the academic cycle wallet
     */
    status: StudentPaymentStatusKey;

    /**
     * Not set from frontend - Identifier of the associated academic cycle
     */
    academicCycleId: string;
    /**
     * Not set from frontend - Reference to the associated academic cycle
     */
    academicCycle?: AcademicCycle;

    /**
     * Not set from frontend - Identifier of the associated student
     */
    studentId: string;
    /**
     * Not set from frontend - Reference to the associated student
     */
    student?: Student;

    /**
     * Not set from frontend - Identifier of the associated academic cycle wallet payment concept
     */
    academicCycleWalletId: string;
    /**
     * Not set from frontend - Reference to the associated academic cycle wallet payment concept
     */
    academicCycleWallet?: AcademicCycleWallet;
}
