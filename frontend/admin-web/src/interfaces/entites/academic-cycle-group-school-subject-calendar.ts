/**
 * Represents the schedule for a specific school subject within an academic cycle group, containing details about the day of the week, class schedule, and references to related entities such as the academic cycle and academic cycle group.
 */
export interface AcademicCycleGroupSchoolSubjectCalendar {
    /**
     * Required - Unique identifier for the academic cycle group school subject calendar, generated by backend
     */
    id: string;
    /**
     * Required - Day of the week for the academic cycle group school subject calendar, represented as a key from the DayOfWeekKey type (e.g., "monday", "tuesday", etc.)
     */
    day: DayOfWeekKey;
    /**
     * Required - Start time of the class for the academic cycle group school subject calendar, represented as an ISO string (HH:mm:ss)
     */
    startTime: string;
    /**
     * Required - End time of the class for the academic cycle group school subject calendar, represented as an ISO string (HH:mm:ss)
     */
    endTime: string;

    /**
     * Required - Identifier of the associated academic cycle
     */
    academicCycleId: string;
    /**
     * Not set from frontend - Reference to the associated academic cycle
     */
    academicCycle?: AcademicCycle;

    /**
     * Required - Identifier of the associated academic cycle group
     */
    academicCycleGroupId: string;
    /**
     * Not set from frontend - Reference to the associated academic cycle group
     */
    academicCycleGroup?: AcademicCycleGroup;
}