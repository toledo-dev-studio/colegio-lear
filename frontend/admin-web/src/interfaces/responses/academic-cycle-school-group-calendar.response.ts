import type { EmployeeResponse } from "./employee.response";
import type { SchoolSubjectResponse } from "./school-subject.response";
import type { AcademicCycleResponse } from "./academic-cycle.response";
import type { DayOfWeekKey } from "@/lib/key-value-pairs/key-value-pair";
import type { AcademicCycleSchoolGroupResponse } from "./academic-cycle-school-group.response";

/**
 * Type: Response
 * Description: Represents the schedule for a specific school subject within an academic cycle group, containing details about the day of the week, class schedule, and references to related entities such as the academic cycle and academic cycle group.
 */
export interface AcademicCycleSchoolGroupCalendarResponse {
    /**
     * Unique identifier for the academic cycle group school subject calendar, generated by backend
     */
    id: string;
    /**
     * Day of the week for the academic cycle group school subject calendar, represented as a key from the DayOfWeekKey type (e.g., "monday", "tuesday", etc.)
     */
    day: DayOfWeekKey;
    /**
     * Start time of the class for the academic cycle group school subject calendar, represented as an ISO string (HH:mm:ss)
     */
    startTime: string;
    /**
     * End time of the class for the academic cycle group school subject calendar, represented as an ISO string (HH:mm:ss)
     */
    endTime: string;
    /**
     * Identifier of the associated academic cycle
     */
    academicCycleId: string;
    /**
     * Reference to the associated academic cycle
     */
    academicCycle?: AcademicCycleResponse;
    /**
     * Identifier of the associated academic cycle group
     */
    academicCycleSchoolGroupId: string;
    /**
     * Reference to the associated academic cycle group
     */
    academicCycleSchoolGroup?: AcademicCycleSchoolGroupResponse;
    /**
     * Identifier of the associated school subject
     */
    schoolSubjectId: string;
    /**
     * Reference to the associated school subject
     */
    schoolSubject?: SchoolSubjectResponse;
    /**
     * Identifier of the associated teacher (employee)
     */
    teacherId: string;
    /**
     * Reference to the associated teacher (employee)
     */
    teacher?: EmployeeResponse;
}
