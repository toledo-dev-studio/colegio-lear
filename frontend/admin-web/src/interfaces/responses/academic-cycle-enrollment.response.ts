import type { StudentResponse } from "./student.response";
import type { ScholarshipResponse } from "./scholarship.response";
import type { AcademicCycleResponse } from "./academic-cycle.response";
import type { AcademicCycleSchoolGroupResponse } from "./academic-cycle-school-group.response";
import type { AcademicCycleEnrollmentStatusKey } from "@/lib/key-value-pairs/key-value-pair-types";

/**
 * Type: Response
 * Description: Represents the enrollment of a student in a specific academic cycle group, containing details about the enrollment status, related entities, and timestamps for record management.
 */
export interface AcademicCycleEnrollmentResponse {
    /**
     * Unique identifier for the student group enrollment, generated by backend
     */
    id: string;
    /**
     * Academic cycle enrollment code, generated by backend
     */
    code: string;
    /**
     * Current status of the student group enrollment
     */
    status: AcademicCycleEnrollmentStatusKey;
    /**
     * Additional notes about the student group enrollment
     */
    observations?: string;
    /**
     * Notes about "dropped" status for a student.
     */
    droppedNotes?: string;
    /**
     * Timestamp when the record was created as an ISO string (YYYY-MM-DDTHH:mm:ss.mmmZ)
     * Backend should set this field when creating a new record, frontend should not set this field when creating or updating a record
     */
    createdAt?: string;
    /**
     * Timestamp when the record was last updated as an ISO string (YYYY-MM-DDTHH:mm:ss.mmmZ)
     * Backend should set this field when updating a record, frontend should not set this field when creating or updating a record
     */
    updatedAt?: string;
    /**
     * Identifier of the associated student
     */
    studentId: string;
    /**
     * Reference to the associated student
     */
    student?: StudentResponse;
    /**
     * Identifier of the associated academic cycle
     */
    academicCycleId: string;
    /**
     * Reference to the associated academic cycle
     */
    academicCycle?: AcademicCycleResponse;
    /**
     * Identifier of the associated academic cycle group
     */
    academicCycleSchoolGroupId: string;
    /**
     * Reference to the associated academic cycle group
     */
    academicCycleSchoolGroup?: AcademicCycleSchoolGroupResponse;
    /**
     * Identifier of the scholarship associated with the student group enrollment, if applicable
     */
    scholarshipId?: string;
    /**
     * Reference to the scholarship associated with the student group enrollment, if applicable
     */
    scholarship?: ScholarshipResponse;
}
