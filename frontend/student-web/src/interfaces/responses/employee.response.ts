/**
 * Type: Response
 * Description: Represents an employee of the school, containing their personal information, contact details, status, and references to related entities such as their job title and security role.
 */
export interface EmployeeResponse {
    /**
     * Unique identifier for the employee
     */
    id: string;
    /**
     * Name of the employee
     */
    name: string;
    /**
     * First last name of the employee
     */
    firstLastName: string;
    /**
     * Second last name of the employee
     */
    secondLastName?: string;
    /**
     * Phone number of the employee
     */
    phoneNumber: string;
    /**
     * Email address of the employee
     */
    email: string;
    /**
     * Username for the employee to access the system, generated by backend
     */
    username: string;
    /**
     * URL of the employee's profile image. This field can be used to store a link to an image hosted on a cloud storage service or a local server
     */
    avatar?: string;
    /**
     * Employee is active flag
     */
    isActive?: boolean;
    /**
     * Flag to indicate if user must change password for a reset password request
     */
    mustChangePassword: boolean;
    /**
     * Security role unique identifier
     */
    securityRoleId?: string;
    /**
     * Job title unique identifier
     */
    jobTitleId: string;
}
